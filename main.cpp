#include <string>
#include <vector>

void is_palindrome() {
    std::string text = "level";
    bool palindrome = true;
    for (std::size_t i = 0; i < text.size() / 2; ++i) {
        if (text[i] != text[text.size() - 1 - i]) { palindrome = false; break; }
    }
    (void)palindrome;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void binomial_small() {
    int n = 6, k = 2;
    int result = 1;
    for (int i = 1; i <= k; ++i) result = result * (n - k + i) / i;
    (void)result;
}

void gcd_triple() {
    int a = 24, b = 36, c = 60;
    int g = a;
    for (int d = g; d >= 1; --d) {
        if (a % d == 0 && b % d == 0 && c % d == 0) { g = d; break; }
    }
    (void)g;
}

extern "C" int gentle_thicket();
extern "C" void cobalt_marble();
extern "C" void gentle_spruce();
extern "C" void verdant_cove();

int main() {
    is_palindrome();
    text_contains();
    binomial_small();
    gcd_triple();
    cobalt_marble();
    gentle_spruce();
    verdant_cove();
    return gentle_thicket();
}
